#!/usr/bin/env bash
# install-snort.sh — let HYEONGI run Snort 3 as its signature sensor.
#
#   sudo bash packaging/install-snort.sh [--iface IFACE] [--base /path/snort.lua] [--community]
#   sudo bash packaging/install-snort.sh --uninstall
#
# Your own snort.lua is never modified. A HYEONGI config is generated at
# /etc/hyeongi/snort/hyeongi.lua that INCLUDES your base snort.lua and then adds:
#   * JSON alerts (alert_json) for the hyeongid IDS bridge
#   * the port_scan inspector + Snort's built-in rules (scan detection)
#   * HYEONGI's local.rules (+ Snort 3 community rules with --community)
# The result is validated with `snort -T` before the service is enabled.

set -euo pipefail
[[ $EUID -eq 0 ]] || { echo "run with sudo." >&2; exit 1; }

HERE="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
. "$HERE/lib/common.sh"
ROOT="$(cd "$HERE/.." && pwd)"
SDIR=/etc/hyeongi/snort
LOGDIR=/var/log/hyeongi/snort
ALERT="$LOGDIR/alert_json.txt"
UNIT=/etc/systemd/system/hyeongi-ids.service
CONF=/etc/hyeongi/hyeongi.yaml
COMMUNITY_URL="https://www.snort.org/downloads/community/snort3-community-rules.tar.gz"

if [[ "${1:-}" == "--uninstall" ]]; then
  systemctl disable --now hyeongi-ids 2>/dev/null || true
  rm -f "$UNIT"; systemctl daemon-reload
  echo "hyeongi-ids removed. $SDIR and $LOGDIR are kept."
  exit 0
fi

IFACE=""; BASE=""; COMMUNITY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --iface)     IFACE="$2"; shift 2 ;;
    --base)      BASE="$2"; shift 2 ;;
    --community) COMMUNITY=1; shift ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done
[[ -z "$IFACE" ]] && IFACE="$(ip -o -4 route show default | awk '{print $5; exit}')"

# --- find snort + its base config ------------------------------------------------
SNORT="$(command -v snort || true)"
[[ -z "$SNORT" && -x /usr/local/bin/snort ]] && SNORT=/usr/local/bin/snort
if [[ -z "$SNORT" ]]; then
  echo "Snort 3 not found (looked in PATH and /usr/local/bin)." >&2
  case "$(distro_family)" in
    arch) echo "  Arch: install 'snort' from the AUR, or use Suricata (see docs/linux.md)." >&2 ;;
    *)    echo "  Most distros don't package Snort 3; build it from https://github.com/snort3/snort3" >&2
          echo "  or use Suricata instead:  $(pkg_install_cmd) suricata   (see docs/linux.md)" >&2 ;;
  esac
  exit 1
fi
"$SNORT" -V 2>&1 | grep -q "Version 3" || { echo "this needs Snort 3:"; "$SNORT" -V 2>&1 | head -5; exit 1; } >&2

if [[ -z "$BASE" ]]; then
  for c in "$(dirname "$SNORT")/../etc/snort/snort.lua" \
           /usr/local/etc/snort/snort.lua /etc/snort/snort.lua; do
    [[ -f "$c" ]] && { BASE="$(readlink -f "$c")"; break; }
  done
fi
[[ -f "$BASE" ]] || { echo "base snort.lua not found — pass it: --base /path/to/snort.lua" >&2; exit 1; }
echo "[i] snort : $SNORT"
echo "[i] base  : $BASE"
echo "[i] iface : $IFACE"

# --- rules -----------------------------------------------------------------------
mkdir -p "$SDIR" "$LOGDIR"
if [[ -f "$SDIR/local.rules" ]]; then
  echo "[=] keeping existing $SDIR/local.rules"
else
  cp "$HERE/snort/local.rules" "$SDIR/local.rules"
fi
if [[ $COMMUNITY -eq 1 ]]; then
  echo "[i] downloading Snort 3 community rules..."
  TMP="$(mktemp -d)"
  curl -fsSL "$COMMUNITY_URL" -o "$TMP/c.tgz" && tar -xzf "$TMP/c.tgz" -C "$TMP" \
    && f="$(find "$TMP" -name 'snort3-community.rules' | head -1)" && [[ -n "$f" ]] \
    && cp "$f" "$SDIR/snort3-community.rules" && echo "[+] community rules installed" \
    || echo "[!] community rules download failed — continuing with local rules only"
  rm -rf "$TMP"
fi

RULES="include $SDIR/local.rules"
[[ -f "$SDIR/snort3-community.rules" ]] && RULES="$RULES
include $SDIR/snort3-community.rules"

# --- generate hyeongi.lua; validate; fall back without port_scan if needed --------
gen() {  # $1 = 1 to enable port_scan, $2 = 1 to rate-limit flood alerts
  {
    echo "-- generated by HYEONGI install-snort.sh — do not edit; re-run the script"
    echo "include '$BASE'"
    echo ""
    echo "alert_json = { file = true, limit = 100,"
    echo "  fields = 'timestamp proto src_addr src_port dst_addr dst_port msg gid sid' }"
    [[ "$1" == 1 ]] && echo "port_scan = default_med_port_scan"
    if [[ "${2:-1}" == 1 ]]; then
      # detection_filter fires on EVERY packet once the threshold is passed, so
      # one flood wrote ~290,000 alerts (190 MB). One alert per source per
      # minute is enough to detect, block and re-block after block_timeout.
      echo "event_filter = event_filter or { }"
      echo "table.insert(event_filter, { gid = 1, sid = 1100010, type = 'limit', track = 'by_src', count = 1, seconds = 60 })"
      echo "table.insert(event_filter, { gid = 1, sid = 1100011, type = 'limit', track = 'by_src', count = 1, seconds = 60 })"
    fi
    echo ""
    echo "ips = ips or {}"
    echo "ips.enable_builtin_rules = true"
    echo "ips.rules = (ips.rules or '') .. [["
    echo "$RULES"
    echo "]]"
  } > "$SDIR/hyeongi.lua"
}

validate() { "$SNORT" -c "$SDIR/hyeongi.lua" -T -q >"$SDIR/validate.log" 2>&1; }

ok=""
for combo in "1 1:port_scan + flood alert limit" "0 1:flood alert limit, no port_scan" \
             "1 0:port_scan, no flood alert limit" "0 0:neither port_scan nor flood alert limit"; do
  args="${combo%%:*}"; what="${combo#*:}"
  gen $args
  if validate; then ok="$what"; break; fi
  echo "[!] snort -T rejected the config with $what — trying the next variant"
done
if [[ -z "$ok" ]]; then
  echo "[x] snort -T rejected the config. Last lines of $SDIR/validate.log:" >&2
  tail -15 "$SDIR/validate.log" >&2
  exit 1
fi
echo "[+] snort -T: config OK ($ok)"

# --- service -------------------------------------------------------------------
sed -e "s|__SNORT__|$SNORT|g" -e "s|__IFACE__|$IFACE|g" "$HERE/hyeongi-ids.service" > "$UNIT"
chmod 0644 "$UNIT"
systemctl daemon-reload
systemctl enable hyeongi-ids >/dev/null 2>&1
systemctl restart hyeongi-ids

# --- point the bridge + triage at the new alert file ------------------------------
if [[ -f "$CONF" ]]; then
  cp "$CONF" "$CONF.bak"
  # only the ids: and triage: sections; ml: has its own alert_file (ML detections)
  sed -i -E "/^(ids|triage):/,/^[^[:space:]#]/ s|^  alert_file: .*|  alert_file: $ALERT|" "$CONF"
  echo "[+] $CONF: alert_file -> $ALERT  (previous saved as $CONF.bak)"
  systemctl restart hyeongid 2>/dev/null || true
fi

sleep 3
echo
echo "hyeongi-ids   : $(systemctl is-active hyeongi-ids || true)"
echo "hyeongid    : $(systemctl is-active hyeongid || true)"
echo "alerts        : $ALERT"
echo "rules         : $SDIR/local.rules (edit, then: sudo systemctl restart hyeongi-ids)"
